/** The edition with its text swapped for the requested language. */
export function localizeEdition(edition: Edition, locale: Locale): Edition {
  const t = locale === "ru" ? RU[edition.slug] : undefined;
  if (!t) return edition;
  const zip = <A, B>(base: A[], tr: B[] | undefined, merge: (a: A, b: B) => A) =>
    tr ? base.map((a, i) => (tr[i] ? merge(a, tr[i]) : a)) : base;

  return {
    ...edition,
    name: t.name ?? edition.name,
    city: t.city ?? edition.city,
    country: t.country ?? edition.country,
    host: t.host ?? edition.host,
    dateLabel: t.dateLabel ?? edition.dateLabel,
    shortDateLabel: t.shortDateLabel ?? edition.shortDateLabel,
    tagline: t.tagline ?? edition.tagline,
    summary: t.summary ?? edition.summary,
    includes: t.includes ?? edition.includes,
    notIncluded: t.notIncluded ?? edition.notIncluded,
    faqs: t.faqs ?? edition.faqs,
    highlights: zip(edition.highlights, t.highlights, (a, b) => ({ ...a, ...b })),
    itinerary: zip(edition.itinerary, t.itinerary, (a, b) => ({ ...a, ...b })),
    hostStory:
      edition.hostStory && t.hostStory
        ? {
            ...edition.hostStory,
            body: t.hostStory.body,
            facts: edition.hostStory.facts.map(([v, l], i) => [v, t.hostStory!.facts[i] ?? l] as [string, string]),
          }
        : edition.hostStory,
    stay: edition.stay && t.stay ? { ...edition.stay, ...t.stay } : edition.stay,
    journey: edition.journey
      ? {
          start: { ...edition.journey.start, name: t.journeyStart ?? edition.journey.start.name },
          stops: zip(edition.journey.stops, t.journey, (a, b) => ({ ...a, ...b })),
        }
      : undefined,
    price: edition.price && t.priceLabel ? { ...edition.price, label: t.priceLabel } : edition.price,
    subjects: edition.subjects,
  };
}

