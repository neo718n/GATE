import { getLocale } from "@/lib/i18n/server";
import type { Locale } from "@/lib/i18n/config";
import {
  ShieldCheck,
  ShieldAlert,
  ShieldX,
  CalendarDays,
  Award as AwardIcon,
  Hash,
  GraduationCap,
  ArrowLeft,
} from "lucide-react";
import type { LookupStatus, PublicCertificate } from "@/lib/certificates/types";
import { AWARD_LABELS as TIER_LABELS, AWARD_CLASSES as TIER_CLASSES } from "@/lib/awards";
import { PrintButton } from "./print-button";

function formatDate(iso: string, locale: Locale = "en"): string {
  return new Date(iso).toLocaleDateString(locale === "ru" ? "ru-RU" : "en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

